    check("sans nouvel article : le retour se fait tout seul après un instant", ev("__jeu.G.mode") == "reussite")
    ev("__jeu.actionReussite('carte')")
    check("« retour à la carte »", ev("__jeu.G.mode") == "carte" and ev("__jeu.G.carteSel") == 1)
    # --- tailles des clients
    ev("__jeu.G.camp = __jeu.campVide(); __jeu.G.resto = 3; __jeu.G.libre = false; __jeu.G.difficile = 0; __jeu.start()")
    # --- chantier 9C
    ev("localStorage.clear(); __jeu.G.camp = __jeu.campVide(); __jeu.G.camp.restos.forEach((r, i) => r.ouvert = i < 3); __jeu.G.libre = false; __jeu.G.difficile = 1; __jeu.G.resto = 2; __jeu.G.mode = 'title'; __jeu.rendre()")
    pg.screenshot(path=out + "/9c_titre_salle.png")
    check("écran de choix : la salle du resto 3 est dessinée en fond (pas d'erreur)", not errs, str(errs[:3]))
    ev("__jeu.G.resto = 0; __jeu.G.difficile = 0; __jeu.start(); __jeu.avancer(1)")
    h = [ev(f"(() => {{ __jeu.G.resto = {i}; __jeu.G.mode = 'play'; __jeu.start(); __jeu.rendre(); return __jeu.PASSES[{i}].bas; }})()") for i in range(4)]
    check("passe-plats : resto 1 sur le mur (292), restos 2 à 4 redescendus (422)", h == [292, 422, 422, 422], str(h))
    ev("__jeu.G.resto = 1; __jeu.start(); __jeu.rendre()")
    check("la zone du passe-plats suit le dessin (rebord à 422)", abs(ev("__jeu.HATCH_RECT.y + __jeu.HATCH_RECT.h") - 422) <= 2, str(ev("__jeu.HATCH_RECT.y + __jeu.HATCH_RECT.h")))
    ev("__jeu.G.camp = __jeu.campVide(); __jeu.G.camp.restos[1].ouvert = true; __jeu.G.camp.restos[2].ouvert = true; __jeu.G.mode = 'accueil'; __jeu.G.accueilResto = 0")
    # accueil : au démarrage, le resto le plus avancé (recalculé au chargement : on le simule via la même formule)
    check("empreinte : le bon code est reconnu, un autre non", ev("__jeu.empreinte('granger-debug')") == 3907671663882622 and ev("__jeu.empreinte('Granger-debug')") != 3907671663882622)
    src = open(os.path.join(jeu, "js", "game.js"), encoding="utf-8").read()
    check("le code n'est pas écrit en clair dans le fichier du jeu", "granger-debug" not in src)
    ev("localStorage.clear(); __jeu.G.camp = __jeu.campVide(); __jeu.G.mode = 'accueil'; __jeu.rendre()")
    pg.mouse.click(1920 - 18, 1080 - 18)
    # chantier 10 : avec js/compte.js, le point caché ouvre la fenêtre de l'enseignante (⚙) ; l'ancienne saisie de code reste dans le jeu (secours) et se teste en l'ouvrant directement
    check("point caché sur l'accueil : ouvre la fenêtre de l'enseignante", ev("document.getElementById('rc-prof').className") == "" and ev("RESTO_JEU.bloque()") is True)
    ev("RESTO_COMPTE.fermerProf(); __jeu.G.retourDe = 'accueil'; __jeu.G.mode = 'mdp'; __jeu.G.saisieMdp = ''; __jeu.G.mdpErr = ''")
    check("l'ancienne saisie du code reste disponible", ev("__jeu.G.mode") == "mdp")
