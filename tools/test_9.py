    pg.on("console", lambda m: logs.append(m.text))
    for ch in "granger-debug":
        pg.keyboard.press(ch)
    ev("__jeu.rendre()"); pg.screenshot(path=out + "/9c_code.png")
    pg.keyboard.press("Enter")
